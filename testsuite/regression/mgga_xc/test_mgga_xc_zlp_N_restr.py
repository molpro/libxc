    ns = pylibxc.array_backend.array_namespace(out["zk"])
    tgt = out["zk"].flatten()
    ref_tgt = ns.full_like(tgt, ns.asarray([-5.693500684295438e+00, -5.239757214612768e+00, -4.863896295151754e+00, -4.519593632294606e+00, -4.168537500548279e+00, -3.778651212333615e+00, -3.325472770652897e+00, -2.797454028105644e+00, -2.204716440273415e+00, -1.583647567827356e+00, -9.725972890896993e-01, -6.599353779243295e-01, -6.312604909236444e-01, -5.133090404773998e-01, -3.554669262049630e-01, -2.112649669804994e-01, -1.182661519325001e-01, -1.014330229955936e-01, -2.540561726322634e-01, -1.533815719925632e+00]))
