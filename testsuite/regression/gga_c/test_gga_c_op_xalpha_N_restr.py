
import pylibxc
import pytest
from pylibxc.example_densities import test_data


def test_gga_c_op_xalpha_N_restr_1_zk():
    # Prepare the input
    inp = test_data["N_restr"]

    # Get the functional
    feval = pylibxc.LibXCFunctional("gga_c_op_xalpha", 1)
    if not feval._have_exc:
        pytest.skip("build lacks the derivative order for zk")

    # Evaluate only up to the tested field's derivative order. Computing higher
    # orders than this test checks is wasteful and can trip a latent bug in an
    # order the test does not exercise (e.g. an fxc segfault under a vrho test).
    out = feval.compute(inp, do_exc=feval._have_exc, do_vxc=False, do_fxc=False, do_kxc=False, do_lxc=False)
    ns = pylibxc.array_backend.array_namespace(out["zk"])
    tgt = out["zk"].flatten()
    ref_tgt = ns.full_like(tgt, ns.asarray([-5.223804809078093e-02, -5.216695592201392e-02, -5.206257518590963e-02, -5.190796900340700e-02, -5.167611456402575e-02, -5.132231783322776e-02, -5.076929181163493e-02, -4.987639950135485e-02, -4.837606618701368e-02, -4.577437079127570e-02, -4.161529083272087e-02, -3.791763585492228e-02, -3.617909304473832e-02, -3.324873164074880e-02, -2.778109830582111e-02, -1.965943435549332e-02, -1.054823744511146e-02, -3.795342525335840e-03, -8.211315436763137e-04, -9.171277433569311e-05]))
    error = ns.max(ns.abs(tgt-ref_tgt))/(1.0+ns.max(ns.asarray([ns.abs(tgt), ns.abs(ref_tgt)])))
    assert error < 5e-08


