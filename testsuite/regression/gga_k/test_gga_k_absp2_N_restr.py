    ns = pylibxc.array_backend.array_namespace(out["zk"])
    tgt = out["zk"].flatten()
    ref_tgt = ns.full_like(tgt, ns.asarray([-5.892313522690195e+00, -4.728772833777065e+00, -3.143080628447970e+00, -1.032412435225319e+00, 1.683607192474384e+00, 5.012654278355897e+00, 8.813925805596458e+00, 1.270527289883961e+01, 1.592095230576268e+01, 1.665052497475097e+01, 9.646993216421588e+00, 2.506007216073524e-01, -2.202352282660869e-01, 2.500895299904595e-01, 5.852682239508586e-01, 7.030043991237263e-01, 6.947025014878739e-01, 6.453611510528857e-01, 6.027447758212243e-01, 5.742316662623144e-01]))
