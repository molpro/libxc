
import pylibxc
import pytest
from pylibxc.example_densities import test_data


def test_gga_x_lb_N_restr_1_vrho():
    # Prepare the input
    inp = test_data["N_restr"]

    # Get the functional
    feval = pylibxc.LibXCFunctional("gga_x_lb", 1)
    if not feval._have_vxc:
        pytest.skip("build lacks the derivative order for vrho")

    # Evaluate only up to the tested field's derivative order. Computing higher
    # orders than this test checks is wasteful and can trip a latent bug in an
    # order the test does not exercise (e.g. an fxc segfault under a vrho test).
    out = feval.compute(inp, do_exc=feval._have_exc, do_vxc=feval._have_vxc, do_fxc=False, do_kxc=False, do_lxc=False)
    ns = pylibxc.array_backend.array_namespace(out["vrho"])
    tgt = out["vrho"].flatten()
    ref_tgt = ns.full_like(tgt, ns.asarray([-6.717284045887260e+00, -6.610644915754132e+00, -6.461012496876599e+00, -6.253308660962124e+00, -5.969395616725915e+00, -5.589639181552639e+00, -5.096741836709328e+00, -4.482353987864808e+00, -3.754436878520345e+00, -2.934128882800674e+00, -2.004253725205212e+00, -1.083489843673898e+00, -8.561841338138864e-01, -7.854444654407552e-01, -6.254876614865017e-01, -4.385532140479647e-01, -2.810551391091271e-01, -1.752119568349183e-01, -1.151907525504013e-01, -8.088749903742579e-02]))
    error = ns.max(ns.abs(tgt-ref_tgt))/(1.0+ns.max(ns.asarray([ns.abs(tgt), ns.abs(ref_tgt)])))
    assert error < 5e-05


