
import pylibxc
import pytest
from pylibxc.example_densities import test_data


def test_gga_x_lbm_N_restr_1_vrho():
    # Prepare the input
    inp = test_data["N_restr"]

    # Get the functional
    feval = pylibxc.LibXCFunctional("gga_x_lbm", 1)
    if not feval._have_vxc:
        pytest.skip("build lacks the derivative order for vrho")

    # Evaluate only up to the tested field's derivative order. Computing higher
    # orders than this test checks is wasteful and can trip a latent bug in an
    # order the test does not exercise (e.g. an fxc segfault under a vrho test).
    out = feval.compute(inp, do_exc=feval._have_exc, do_vxc=feval._have_vxc, do_fxc=False, do_kxc=False, do_lxc=False)
    ns = pylibxc.array_backend.array_namespace(out["vrho"])
    tgt = out["vrho"].flatten()
    ref_tgt = ns.full_like(tgt, ns.asarray([-6.976878491096351e+00, -6.848708160519749e+00, -6.669306443311306e+00, -6.421196911282371e+00, -6.083956563018697e+00, -5.636835541480804e+00, -5.064774859954303e+00, -4.368819849796384e+00, -3.578157615579667e+00, -2.745333145315154e+00, -1.866597109002817e+00, -1.087612086063644e+00, -9.080165164511315e-01, -7.767444006738280e-01, -5.899015477036015e-01, -4.077260073146569e-01, -2.684608341846261e-01, -1.735065043705550e-01, -1.164229253634452e-01, -8.102373854507114e-02]))
    error = ns.max(ns.abs(tgt-ref_tgt))/(1.0+ns.max(ns.asarray([ns.abs(tgt), ns.abs(ref_tgt)])))
    assert error < 5e-05


